#!/usr/bin/env python3
"""Writes crates/emberwave-core/src/encode/weights.rs: the distortion weight of
every band, which the encoder's rate control multiplies squared coefficient
errors by.

The weight of a band is (csf * 2^b)^2 / 256, where b is the band's bit
exponent before the cap (encode/quant.rs, band_exponent), so 4^b follows the
energy the inverse transform gives a coefficient error of the band, and csf is
the Mannos-Sakrison contrast sensitivity function

    csf(f) = 2.6 (0.0192 + 0.114 f) exp(-(0.114 f)^1.1)

at the band's spatial frequency f in cycles per degree:
f = max(8, 32.64 * sqrt(h^2 + v^2) / 2^level), with h and v the middle of the
band's frequency range in each direction (0.25 for low-pass, 0.75 for
high-pass). Chroma of 4:2:0 below the coarsest level gets 0.6 of the weight's
csf. This is the weighting upstream's encoder uses, so that rate control
spends bits where the two encoders agree they show.

The weights are computed here once, in double precision, and committed as f32
literals, so that the CPU and GPU encoders use the same values on every
system (decision D28).

Usage: scripts/gen_encoder_weights.py > crates/emberwave-core/src/encode/weights.rs
"""

import math
import struct

CLASSES = ["luma", "4:2:0 chroma", "4:4:4 chroma"]
BANDS = ["LL", "HL", "LH", "HH"]
LEVELS = 5


def exponent(chroma: bool, level: int, band: int) -> int:
    return 8 + [2, 1, 1, 0][band] + level - (1 if chroma else 0)


def csf(f: float) -> float:
    return 2.6 * (0.0192 + 0.114 * f) * math.exp(-((0.114 * f) ** 1.1))


def weight(cls: int, level: int, band: int) -> float:
    h = 0.75 if band in (1, 3) else 0.25
    v = 0.75 if band in (2, 3) else 0.25
    f = max(8.0, 32.64 * math.sqrt(h * h + v * v) / 2**level)
    sensitivity = csf(f)
    if cls == 1 and level < LEVELS - 1:
        sensitivity *= 0.6
    b = exponent(cls != 0, level, band)
    return (sensitivity * 2.0**b) ** 2 / 256.0


def as_f32(x: float) -> float:
    return struct.unpack("<f", struct.pack("<f", x))[0]


def literal(x: float) -> str:
    """The shortest decimal that reads back as the same f32."""
    value = as_f32(x)
    for digits in range(1, 10):
        text = f"{value:.{digits}e}"
        if as_f32(float(text)) == value:
            return text
    raise ValueError(x)


def main() -> None:
    print("//! Distortion weights of the bands, per component class, level and band.")
    print("//!")
    print("//! Generated by `scripts/gen_encoder_weights.py`, which explains the formula;")
    print("//! do not edit. Committed as `f32` literals so that every system and the GPU")
    print("//! use the same values (decision D28).")
    print()
    print("/// Indexed by class (luma, 4:2:0 chroma, 4:4:4 chroma), level (0 finest)")
    print("/// and band (LL, HL, LH, HH).")
    print("pub(crate) const WEIGHTS: [[[f32; 4]; 5]; 3] = [")
    for cls, name in enumerate(CLASSES):
        print(f"    // {name}")
        print("    [")
        for level in range(LEVELS):
            values = ", ".join(literal(weight(cls, level, band)) for band in range(4))
            print(f"        [{values}],")
        print("    ],")
    print("];")


if __name__ == "__main__":
    main()
